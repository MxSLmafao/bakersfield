#!/usr/bin/env bash
# Write checksums and sizes of every binary asset.
#
# Usage (from the repository root): handoff/scripts/make-asset-manifest.sh
# Output:
#   handoff/reference/ASSET-MANIFEST.md   readable summary
#   handoff/reference/ASSETS.sha256       every file, in sha256sum format
#
# To check a copy of the assets:  sha256sum -c handoff/reference/ASSETS.sha256
set -euo pipefail

REF="handoff/reference"
mkdir -p "$REF"

LIST=$(git ls-files 'assets/**' 'public/**' 'src/app/icon.png' 'src/app/apple-icon.png' \
  | grep -v '\.md$' | sort)

echo "$LIST" | xargs sha256sum > "$REF/ASSETS.sha256"

python3 - "$REF" <<'EOF'
import os, subprocess, sys, json, collections
from PIL import Image

ref = sys.argv[1]
rows = [l.rstrip("\n").split("  ", 1) for l in open(os.path.join(ref, "ASSETS.sha256"))]

def probe(path):
    out = subprocess.run(
        ["ffprobe", "-v", "error", "-select_streams", "v:0", "-count_frames",
         "-show_entries", "stream=width,height,r_frame_rate,nb_read_frames,codec_name",
         "-show_entries", "format=duration", "-of", "json", path],
        capture_output=True, text=True).stdout
    d = json.loads(out); s = d["streams"][0]
    return "%s %sx%s, %s fps, %s frames, %.1f s" % (
        s["codec_name"], s["width"], s["height"], s["r_frame_rate"].split("/")[0],
        s["nb_read_frames"], float(d["format"]["duration"]))

def dims(path):
    if path.endswith(".mp4"):
        return probe(path)
    with Image.open(path) as im:
        return "%s %dx%d" % (im.format, im.size[0], im.size[1])

single, groups = [], collections.OrderedDict()
for sha, path in rows:
    parts = path.split("/")
    if parts[0] == "public" and parts[1] in ("frames", "frames-sm", "pov", "pov-sm"):
        groups.setdefault("/".join(parts[:3]), []).append((sha, path))
    else:
        single.append((sha, path))

with open(os.path.join(ref, "ASSET-MANIFEST.md"), "w") as f:
    head = subprocess.run(["git", "rev-parse", "--short", "HEAD"], capture_output=True, text=True).stdout.strip()
    f.write("# Asset manifest\n\n")
    f.write("Generated by `handoff/scripts/make-asset-manifest.sh` from commit `%s`.\n\n" % head)
    f.write("Every file is also listed in `ASSETS.sha256` in `sha256sum` format. To check a copy:\n\n")
    f.write("```bash\nsha256sum -c handoff/reference/ASSETS.sha256\n```\n\n")
    f.write("## Single files\n\n| Path | Format and size | Bytes | SHA-256 (first 16) |\n|---|---|---|---|\n")
    for sha, path in single:
        f.write("| `%s` | %s | %d | `%s` |\n" % (path, dims(path), os.path.getsize(path), sha[:16]))
    f.write("\n## Frame folders\n\n")
    f.write("Each folder holds numbered frames `0001.webp…` and `poster.webp` (a copy of the last frame).\n\n")
    f.write("| Folder | Files | Frame size | Bytes | SHA-256 of first frame (first 16) | SHA-256 of poster (first 16) |\n|---|---|---|---|---|---|\n")
    totals = collections.OrderedDict()
    for folder, items in groups.items():
        size = sum(os.path.getsize(p) for _, p in items)
        first = [s for s, p in items if p.endswith("/0001.webp")][0]
        poster = [s for s, p in items if p.endswith("/poster.webp")][0]
        with Image.open(items[0][1]) as im:
            wh = "%dx%d" % im.size
        f.write("| `%s/` | %d | %s | %d | `%s` | `%s` |\n" % (folder, len(items), wh, size, first[:16], poster[:16]))
        top = "/".join(folder.split("/")[:2])
        t = totals.setdefault(top, [0, 0]); t[0] += len(items); t[1] += size
    f.write("\n## Totals\n\n| Set | Files | Bytes | MB |\n|---|---|---|---|\n")
    for top, (n, b) in totals.items():
        f.write("| `%s/` | %d | %d | %.2f |\n" % (top, n, b, b / 1048576))
    f.write("| all frame sets | %d | %d | %.2f |\n" % (
        sum(v[0] for v in totals.values()), sum(v[1] for v in totals.values()),
        sum(v[1] for v in totals.values()) / 1048576))
print("wrote", os.path.join(ref, "ASSET-MANIFEST.md"), "and ASSETS.sha256 with", len(rows), "files")
EOF
