#!/usr/bin/env bash
# Write every text source file of the site into one Markdown file, so a model
# with no repository access can read the exact code.
#
# Usage (from the repository root): handoff/scripts/make-source-snapshot.sh
# Output: handoff/reference/SOURCE.md
set -euo pipefail

OUT="handoff/reference/SOURCE.md"
mkdir -p "$(dirname "$OUT")"

FILES=$(git ls-files \
  'src/**/*.ts' 'src/**/*.tsx' 'src/**/*.css' \
  'package.json' 'tsconfig.json' 'next.config.mjs' 'eslint.config.mjs' '.gitignore' \
  'assets/brand/BRAND.md' | sort)

{
  echo "# Bakersfield source snapshot"
  echo
  echo "Generated by \`handoff/scripts/make-source-snapshot.sh\` from commit \`$(git rev-parse --short HEAD)\`."
  echo "This file is the ground truth for the code. If a description in another handoff file"
  echo "disagrees with this file, this file is correct."
  echo
  echo "## Files"
  echo
  for f in $FILES; do echo "- \`$f\` ($(wc -l < "$f") lines)"; done
  echo
  for f in $FILES; do
    ext="${f##*.}"
    case "$ext" in
      tsx) lang=tsx ;; ts) lang=ts ;; css) lang=css ;; json) lang=json ;;
      mjs) lang=js ;; md) lang=markdown ;; *) lang=text ;;
    esac
    echo "## \`$f\`"
    echo
    echo "\`\`\`\`$lang"
    cat "$f"
    echo
    echo "\`\`\`\`"
    echo
  done
} > "$OUT"

echo "wrote $OUT ($(wc -l < "$OUT") lines)"
